const fs=require('fs'),assert=require('assert'),path=require('path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
assert(html.includes('id="autoPlayBtn"'),'global AUTO PLAY button exists');
assert(html.includes('games/sevens.js?v=0.6.3'),'Sevens definition is loaded');
assert(html.includes('games/war.js?v=0.6.3'),'War definition is loaded');
assert(html.includes('battle-engine.js?v=0.6.3'),'battle engine is loaded');
